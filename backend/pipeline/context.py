"""Context assembly — gather all contextual information for a conversation turn.

Collects memory, emotion, module context, and conversation history
into a single structure ready for the AI call.
"""

import logging
from dataclasses import dataclass

from drives.engine import drive_engine
from emotion.engine import emotion_engine
from memory.manager import memory_manager
from modules.manager import module_manager

logger = logging.getLogger(__name__)


@dataclass
class ConversationContext:
    """All context assembled for a single conversation turn."""
    memory_context: str
    emotion_context: str
    module_context: str
    history: list[dict]
    mcp_server: object | None  # SdkMcpServer or None
    tool_names: list[str]
    # Self-concept: evolving autobiographical paragraph, regenerated by
    # the consolidator. Empty string if no narrative has been produced yet.
    self_concept: str = ""
    # Theory of mind: what Mika knows/assumes about the current person,
    # plus her pending commitments toward them. Empty if no profile
    # exists yet for this person_id.
    person_context: str = ""


async def gather_context(
    message: str,
    person_id: str,
    include_tools: bool = True,
) -> ConversationContext:
    """Assemble all context needed for an AI conversation turn.

    Args:
        message: The user/trigger message (used for memory retrieval).
        person_id: Who is talking (for emotion + memory boosting).
        include_tools: Whether to include MCP tools from modules.
    """
    # Memory context (graceful degradation)
    try:
        memory_context = await memory_manager.get_memory_context(
            message, person_id=person_id
        )
    except Exception:
        logger.warning("Memory retrieval failed, continuing without context")
        memory_context = ""

    # Self-concept: latest autobiographical narrative from the consolidator.
    # Best-effort — if the table hasn't been populated yet (no narrative
    # generated), we just skip it and the prompt uses personality alone.
    self_concept = await _fetch_self_concept()

    # Theory of mind: profile + pending commitments for the current person.
    # Only meaningful when person_id names an actual Entity in memory.
    person_context = await _fetch_person_context(person_id)

    # Emotion context = Mika's global mood only. The per-person affective
    # stance is relational and belongs to person_context (see below), so
    # the prompt cleanly separates "how Mika feels" from "how Mika feels
    # about this person".
    emotion_context = emotion_engine.get_global_mood_context()

    # Intrinsic drives — still Mika-centric (curiosity / social need / rest),
    # so they attach to the global mood layer.
    # NOTE: drive satisfaction is triggered by conscience.observe() when the
    # chat.message event bubbles up, so we deliberately don't call
    # drive_engine.on_conversation() here to avoid double-counting.
    drive_context = drive_engine.get_context()
    if drive_context:
        emotion_context = (
            f"{emotion_context}\n{drive_context}" if emotion_context else drive_context
        )

    # Module context for system prompt
    module_context = module_manager.collect_context()

    # Conversation history
    history = memory_manager.get_conversation_context()

    # Tools
    mcp_server = None
    tool_names = []
    if include_tools:
        mcp_server = module_manager.get_mcp_server()
        tool_names = module_manager.get_tool_names()

    return ConversationContext(
        memory_context=memory_context,
        emotion_context=emotion_context,
        module_context=module_context,
        history=history,
        mcp_server=mcp_server,
        tool_names=tool_names,
        self_concept=self_concept,
        person_context=person_context,
    )


async def _fetch_self_concept() -> str:
    """Return the most recent self-narrative content, or '' if none."""
    try:
        from asgiref.sync import sync_to_async

        from memory.models import SelfNarrative

        latest = await sync_to_async(
            lambda: SelfNarrative.objects.order_by("-created_at").first()
        )()
        return latest.content if latest and latest.content else ""
    except Exception:
        logger.debug("Self-concept fetch failed", exc_info=True)
        return ""


# System/internal person_ids that never correspond to a real Entity.
# Skipping them avoids a round-trip per conversation turn from internals.
_INTERNAL_PERSON_IDS = frozenset({"conscience_mika", "__global__", "anonymous", ""})


async def _fetch_person_context(person_id: str) -> str:
    """Return a prompt-ready block combining everything Mika knows/feels
    about this specific person:
      - semantic profile (summary, closeness, preferred tone, topics)
      - current affective stance (live PAD oscillator via EmotionEngine)
      - weekly emotional trend (EmotionalSummary)
      - pending commitments toward them

    This block replaces the per-person half of what used to live in
    `emotion_context`. It gives the LLM a unified relational picture.

    Empty string when internal/system person_id, or no data to show.
    """
    if person_id in _INTERNAL_PERSON_IDS:
        return ""

    affect = emotion_engine.get_person_affect_context(person_id)

    try:
        from asgiref.sync import sync_to_async

        from memory.models import Commitment, EmotionalSummary, PersonProfile

        profile = await sync_to_async(
            lambda: PersonProfile.objects
            .select_related("entity")
            .filter(entity__name=person_id, entity__entity_type="person")
            .first()
        )()

        entity = profile.entity if profile else None

        commitments: list[str] = []
        if entity is not None:
            commitments = await sync_to_async(
                lambda: list(
                    Commitment.objects
                    .filter(person=entity, status="pending")
                    .order_by("-created_at")
                    .values_list("description", flat=True)[:5]
                )
            )()

        weekly_trend = await sync_to_async(
            lambda: _summarize_emotional_trend(
                list(
                    EmotionalSummary.objects
                    .filter(person_id=person_id, period_type="daily")
                    .order_by("-period_start")[:7]
                )
            )
        )()

        if (
            not affect
            and profile is None
            and not commitments
            and not weekly_trend
        ):
            return ""

        return _format_person_context(
            profile=profile,
            commitments=commitments,
            affect=affect,
            weekly_trend=weekly_trend,
        )

    except Exception:
        logger.debug("Person-context fetch failed", exc_info=True)
        # If DB failed but we at least have an affect string, return that —
        # it's better than a silent blank about the person.
        return affect


def _format_person_context(
    *, profile, commitments: list[str], affect: str, weekly_trend: str,
) -> str:
    """Assemble a compact French block covering everything Mika knows+feels."""
    lines: list[str] = []

    if profile and profile.summary:
        lines.append(profile.summary)

    if profile:
        extras = []
        if profile.closeness and profile.closeness != "stranger":
            extras.append(f"proximite: {profile.closeness}")
        if profile.preferred_tone and profile.preferred_tone != "unknown":
            extras.append(f"ton prefere avec elle/lui: {profile.preferred_tone}")
        if profile.topics_of_interest:
            extras.append(
                "sujets qui l'interessent: "
                + ", ".join(profile.topics_of_interest[:4])
            )
        if profile.sensitive_topics:
            extras.append(
                "sujets sensibles a manier avec prudence: "
                + ", ".join(profile.sensitive_topics[:3])
            )
        if extras:
            lines.append(" | ".join(extras))

    if affect:
        lines.append(affect)

    if weekly_trend:
        lines.append(weekly_trend)

    if commitments:
        lines.append(
            "Tu lui avais dit: " + "; ".join(c[:120] for c in commitments)
        )

    return "\n".join(lines)


def _summarize_emotional_trend(summaries: list) -> str:
    """Build a short French line from recent EmotionalSummary rows.

    Empty when fewer than 2 days of data — a single-day snapshot isn't
    really a "trend". Returns e.g. "Sur les 5 derniers jours avec elle/lui
    tu as ete majoritairement happy (tendance warming)."
    """
    if not summaries or len(summaries) < 2:
        return ""

    from collections import Counter
    dominant_per_day = [s.dominant_emotion for s in summaries if s.dominant_emotion]
    if not dominant_per_day:
        return ""

    counter = Counter(dominant_per_day)
    top, top_count = counter.most_common(1)[0]
    most_recent = summaries[0]

    if top_count >= len(summaries) * 0.6:
        return (
            f"Sur les {len(summaries)} derniers jours avec elle/lui tu as ete "
            f"majoritairement {top} (tendance recente: {most_recent.trend})."
        )
    return (
        f"Emotions variees avec elle/lui sur {len(summaries)} jours "
        f"(tendance recente: {most_recent.dominant_emotion}, {most_recent.trend})."
    )
